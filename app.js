function esc(v){return String(v??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));}
const yearRows=$('#yearRows'); let rowCount=0;
function addYear(gpa='',credits=''){
  rowCount++; const tr=document.createElement('tr');
  tr.innerHTML=`<td>Year ${rowCount}</td><td><input class="gpa" type="number" min="0" max="4" step="0.01" placeholder="e.g. 3.50" value="${gpa}"></td><td><input class="credits" type="number" min="0.01" step="0.01" placeholder="e.g. 30" value="${credits}"></td>`;
  yearRows.appendChild(tr);
}
for(let i=0;i<4;i++)addYear();
$('#addYear').onclick=()=>addYear();
$('#calculate').onclick=()=>{
  const rows=[...yearRows.querySelectorAll('tr')]; let sum=0,credits=0;
  for(const r of rows){
    const g=r.querySelector('.gpa').value,c=r.querySelector('.credits').value;
    if(g===''&&c==='')continue;
    if(g===''||c===''||Number(g)<0||Number(g)>4||Number(c)<=0){
      $('#calcOutput').classList.remove('hidden');
      $('#calcOutput').textContent='Enter a valid GPA (0–4.00) and positive credits for every filled row.';return;
    }
    sum+=Number(g)*Number(c); credits+=Number(c);
  }
  const out=$('#calcOutput'); out.classList.remove('hidden');
  out.innerHTML=credits?`<small>TOTAL CREDIT-WEIGHTED CGPA</small><br><strong>${(sum/credits).toFixed(2)}</strong><p class="muted">Credits counted: ${credits.toFixed(2)} · Formula: Σ(GPA × credits) / Σ credits</p><button class="outline" id="printCgpa">Print / Save PDF</button>`:'Enter GPA and credits to calculate.';
  const b=$('#printCgpa'); if(b)b.onclick=()=>window.print();
};
